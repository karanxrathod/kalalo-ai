export class PresetsService {
  public static listPresets(filter?: {
    format?: AspectRatio;
    language?: SupportedLanguage;
    category?: "Social" | "Professional" | "Cinematic" | "Educational" | "Accessibility";
  }): PresetStyle[] {
    let result = [...ORIGINAL_PRESETS];

    if (filter?.category) {
      result = result.filter((p) => p.category === filter.category);
    }

    if (filter?.format) {
      result = result.filter((p) => p.supportedAspectRatios.includes(filter.format!));
    }

    if (filter?.language) {
      result = result.filter(
        (p) => !p.targetLanguages || p.targetLanguages.includes(filter.language!)
      );
    }

    return result;
  }

  public static getPreset(id: string): PresetStyle {
    const found = ORIGINAL_PRESETS.find((p) => p.id === id);
    if (!found) {
      throw new KalaloError({
        code: "PRESET_NOT_FOUND",
        message: `Preset with ID "${id}" was not found. Use kalalo_list_presets to see available options.`,
        retryable: false,
        details: { requestedId: id, available: ORIGINAL_PRESETS.map((p) => p.id) },
      });
    }
    return found;
  }
}
